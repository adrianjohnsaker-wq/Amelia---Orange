#!/usr/bin/env python3
"""WE-2 surrogates (REGISTRATION.md). For segment m (1,000 data) and replicate j = 1..49: every position keeps its source, and
each source's zones in the segment are regenerated by a second-order Markov chain of that source's zones fitted on the OTHER
11 segments (leave-one-out), backing off to first order, then to the source's zone frequencies, then to all zones, where a
context was never seen. Start: the source's fitted first-zone frequencies. RNG: random.Random(f'WE2|{m}|{j}').
So a surrogate keeps each source's ordinary order up to two steps, the interleaving of sources and their timing, and nothing else.
  python3 surrogates.py <prepared.json> <out.json>      out: [[real, s1..s49] for m in 0..11]"""
import collections, json, random, sys
D = json.load(open(sys.argv[1])); Z, SRC = D['zones'], D['sources']; L, M, S = 1000, 12, 49
def seg(m): return range(m * L, (m + 1) * L)
def fit(skip):
    c2, c1, c0, first = (collections.defaultdict(collections.Counter) for _ in range(4)); allz = collections.Counter()
    for m in range(M):
        if m == skip: continue
        by = collections.defaultdict(list)
        for t in seg(m): by[SRC[t]].append(Z[t])
        for s, z in by.items():
            first[s][z[0]] += 1; c0[s].update(z); allz.update(z)
            for a, b in zip(z, z[1:]): c1[(s, a)][b] += 1
            for a, b, c in zip(z, z[1:], z[2:]): c2[(s, a, b)][c] += 1
    return c2, c1, c0, first, allz
def draw(rng, *cs):
    for c in cs:
        if c and sum(c.values()): k = sorted(c); return rng.choices(k, weights=[c[x] for x in k])[0]
def surrogate(m, j, model):
    c2, c1, c0, first, allz = model; rng = random.Random(f'WE2|{m}|{j}'); out, hist = [], collections.defaultdict(list)
    for t in seg(m):
        s, h = SRC[t], hist[SRC[t]]
        if not h: z = draw(rng, first.get(s), c0.get(s), allz)
        elif len(h) == 1: z = draw(rng, c1.get((s, h[-1])), c0.get(s), allz)
        else: z = draw(rng, c2.get((s, h[-2], h[-1])), c1.get((s, h[-1])), c0.get(s), allz)
        h.append(z); out.append(z)
    return out
res = []
for m in range(M):
    model = fit(m); res.append([[Z[t] for t in seg(m)]] + [surrogate(m, j, model) for j in range(1, S + 1)])
json.dump(res, open(sys.argv[2], 'w'))
